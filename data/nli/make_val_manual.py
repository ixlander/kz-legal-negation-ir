NUMBER = re.compile(r"^\s*\d+(-\d+)?\.\s*")
SENTENCE = re.compile(r"(?<=[.])\s+(?=[А-ЯЁӘІҢҒҮҰҚӨҺ])")


def chunks(lang):
    out = {}
    for code in ("labor", "tax"):
        for line in open(CORPUS / f"{code}_{lang}.jsonl", encoding="utf-8"):
            r = json.loads(line)
            out[r["chunk_id"]] = r["text"]
    return out


def premise(text, sentence):
    text = NUMBER.sub("", text.replace("\n", " ")).strip()
    return text if sentence is None else SENTENCE.split(text)[sentence]


def main():
    text = {lang: chunks(lang) for lang in ("ru", "kz")}
    rows = []
    for i, (p, label, rng, hyp_ru, hyp_kz) in enumerate(PAIRS, 1):
        cid, sent = PREMISES[p]
        for lang, hyp, status in (("ru", hyp_ru, "draft"), ("kz", hyp_kz, "NEEDS_KZ_CHECK")):
            rows.append({"id": f"{lang}-{i:03d}", "pair_id": f"v{i:03d}", "lang": lang, "chunk_id": cid,
                         "premise": premise(text[lang][cid], sent), "hypothesis": hyp, "label": label,
                         "range": rng, "status": status})
    with open(HERE / "val_manual.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    labels = [r["label"] for r in rows if r["lang"] == "ru"]
    print(f"{len(rows)} rows; per language: {len(labels)} pairs, entailment {labels.count(E)}, "
          f"neutral {labels.count(N)}, contradiction {labels.count(C)}, range {sum(r['range'] for r in rows) // 2}")


if __name__ == "__main__":
    main()
