def main():
    ids = set()
    for code in ("labor", "tax"):
        for lang in ("ru", "kz"):
            ids |= {json.loads(l)["chunk_id"] for l in open(CORPUS / f"{code}_{lang}.jsonl", encoding="utf-8")}
    numbered = [(f"lab_{i}", q) for i, q in enumerate(LABOR, 101)] + [(f"tax_{i}", q) for i, q in enumerate(TAX, 101)]
    rows = []
    for pair, (cell, gold, twin, ru, kz) in numbered:
        missing = [c for c in gold + twin if c not in ids]
        assert not missing, missing
        common = {"pair_id": pair, "slice": "general" if cell == "gen-polar" else "negation", "cell": cell,
                  "gold_ids": gold, "twin_ids": twin}
        rows.append({**common, "qid": f"ru_{pair}", "lang": "ru", "question": ru, "status": "draft"})
        rows.append({**common, "qid": f"kz_{pair}", "lang": "kz", "question": kz, "status": "NEEDS_KZ_CHECK"})
    with open(HERE / "queries_v2_draft.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    cells = {}
    for r in rows[::2]:
        cells[r["cell"]] = cells.get(r["cell"], 0) + 1
    print(len(rows) // 2, "pairs", cells, "with twin:", sum(bool(r["twin_ids"]) for r in rows[::2]))


if __name__ == "__main__":
    main()
